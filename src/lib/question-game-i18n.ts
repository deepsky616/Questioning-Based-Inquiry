export type QuestionGameLocale = "ko" | "en";

export interface LocalizedText {
  ko: string;
  en: string;
}

export function resolveQuestionGameLocale(locale: string): QuestionGameLocale {
  return locale === "en" ? "en" : "ko";
}

export function getLocalizedText(
  value: LocalizedText | undefined,
  locale: string,
  fallback: string,
): string {
  if (!value) return fallback;
  const resolved = resolveQuestionGameLocale(locale);
  return value[resolved] || value.ko || value.en || fallback;
}

export function makeLocalizedText(ko: string, en: string): LocalizedText {
  return { ko, en };
}

