export function buildGradeFiveDesign(session) {
  const lesson = GRADE_FIVE_LESSONS[session.key];
  const guide = GRADE_FIVE_GUIDES[session.key];
  const achievements = lesson.codes.map((code) => {
    const value = achievementByCode.get(code);
    if (!value) throw new Error(`성취기준을 찾을 수 없습니다: ${code}`);
    return value;
  });
  return {
    key: session.key, id: session.unitDesignId, title: lesson.title, subject: lesson.subject,
    gradeRange: "5-6", grade: "5", area: lesson.area, coreIdea: lesson.coreIdea,
    achievements, selectedKeywords: lesson.keywords.map(([term]) => term),
    coreSentences: lesson.sentences, essentialQuestions: lesson.essential,
    inquiryQuestions: ["factual", "conceptual", "controversial"].flatMap((type) =>
      [...lesson.questions, ...(extraDesignQuestions[session.key] ?? [])].filter((item) => item.type === type).slice(0, type === "controversial" ? 1 : 2)
    ).map((item) => ({
      type: item.type, content: item.content, closure: item.closure,
      studentGuide: { meaning: guide.meanings[lesson.questions.indexOf(item)] ?? "자료에서 직접 확인할 수 있는 정보와 그 근거를 찾아보는 질문이에요.", keywords: lesson.keywords.map(([term, meaning]) => ({term, meaning})), thinkingStart: item.hint },
    })),
    learningGuides: {
      coreIdea: { explanation: guide.core, lifeConnection: lesson.life, keywords: lesson.keywords.map(([term, meaning]) => ({term, meaning})) },
      achievements: achievements.map((_, index) => ({ index, explanation: index === 0 ? guide.core : guide.sentences.at(-1) })),
      coreSentences: guide.sentences.map((explanation, index) => ({ index, explanation })),
      essentialQuestions: lesson.essential.map((_, index) => ({ index, thinkingFocus: lesson.questions[index * 2].hint, perspectives: [lesson.life] })),
    },
  };
}

export function gradeFiveComment(question, index = 0) {
  const lesson = Object.values(GRADE_FIVE_LESSONS).find((item) => item.topic === question.context);
  if (!lesson) throw new Error("답변과 연결할 5학년 수업을 찾을 수 없습니다.");
  const item = lesson.questions.find((item) => question.content.includes(item.content));
  if (!item) throw new Error("답변과 연결할 5학년 질문을 찾을 수 없습니다.");
  return index % 2 === 0 ? item.answer : `이렇게 살펴보면 좋겠어요. ${item.hint}`;
}

export function gradeFiveVariedComment(question, index = 0) {
  const entry = Object.entries(GRADE_FIVE_LESSONS).find(([, lesson]) => lesson.topic === question.context);
  const questionIndex = entry?.[1].questions.findIndex(item => question.content.includes(item.content));
  const variants = entry && GRADE_FIVE_COMMENT_VARIANTS[entry[0]]?.[questionIndex];
  if (!variants?.length) throw new Error("댓글과 연결할 5학년 질문을 찾을 수 없습니다.");
  return variants[index % variants.length];
}

